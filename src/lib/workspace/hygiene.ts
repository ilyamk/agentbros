import type { RepositoryText } from "../context/repository";
import path from "node:path";
import { HARNESSES } from "../harness/registry";

export type HygieneFinding = {
  file: string;
  line: number;
  rule: "local-path" | "maintenance-output" | "media-binary" | "harness-link";
  message: string;
};

const HOME_PATH =
  /\/(?:Users|home)\/[A-Za-z0-9][A-Za-z0-9._-]*(?:\/|(?=$|[\s"'`]))|[A-Za-z]:\\+Users\\+[A-Za-z0-9][A-Za-z0-9._-]*(?:\\|(?=$|[\s"'`]))/i;
const WORKTREE_PATH =
  /(?:^|[\s"'`])(?:[A-Za-z]:)?[\\/](?:[\w.-]+[\\/])+\.(?:codex|claude)[\\/](?:worktrees|sessions)[\\/]/;
/** Binary media: kept out of git and fetched from a manifest (docs/assets.md). */
export const MEDIA_BINARY =
  /\.(jpe?g|png|gif|webp|avif|tiff?|psd|mp4|mov|webm|mkv|wav|mp3|m4a|aac|ogg|flac|hdr|exr|glb|gltf|blend|fbx|obj|usdz|ttf|otf|woff2?|lottie)$/i;
/** docs/assets.md inventory row (c): the only media kept in git. */
export const TRACKED_MEDIA_FOLDERS = [
  "docs/readme/",
  "docs/library/previews/",
  "docs/photoreal/",
  "design-reference/device-mockup/",
  "design-reference/screenshots/square/",
  "tests/fixtures/film-chain/track.wav",
];
const OUTPUT_PATH =
  /^(?:out|\.cache|\.contrib|coverage|logs|tmp|temp)\/|^\.(?:codex|claude)\/(?:worktrees|sessions)\/|^docs\/(?:verification|workstreams|archive)\/|(?:^|\/)\.(?:DS_Store|env(?:\.(?!example$)[^/]+)?)$|\.(?:log|cpuprofile|heapprofile|tsbuildinfo)$/;

/** Tracked harness links (`.claude/skills` …) must point at their canonical `.agents/` folder; generated harness files (machine paths) must stay ignored. */
const TRACKED_LINKS = new Map(
  HARNESSES.flatMap((spec) => spec.links.filter((link) => link.path.startsWith(".claude/"))).map((link) => [
    link.path,
    link.target,
  ]),
);
const GENERATED = HARNESSES.flatMap((spec) => [
  ...spec.mcp.filter((target) => target.scope === "project" && !target.committed).map((target) => target.file),
  ...(spec.agents ? [`${spec.agents.dir}/`] : []),
  ...spec.links.filter((link) => !TRACKED_LINKS.has(link.path)).map((link) => link.path),
]);

function harnessFindings(repo: RepositoryText, files: readonly string[]): HygieneFinding[] {
  const findings: HygieneFinding[] = [];
  for (const file of files) {
    const canonical = TRACKED_LINKS.get(file);
    if (canonical !== undefined) {
      const link = repo.linkTarget?.(file);
      const resolved =
        link === undefined
          ? undefined
          : path.posix.normalize(path.posix.join(path.posix.dirname(file), link.replaceAll("\\", "/")));
      if (resolved !== canonical)
        findings.push({
          file,
          line: 0,
          rule: "harness-link",
          message: `Must be a symlink to ${canonical} (never a second copy); pnpm harness:setup --apply repairs it.`,
        });
    }
    if (GENERATED.some((generated) => (generated.endsWith("/") ? file.startsWith(generated) : file === generated)))
      findings.push({
        file,
        line: 0,
        rule: "harness-link",
        message: "Generated by pnpm harness:setup with machine paths; keep it git-ignored (docs/harnesses.md).",
      });
  }
  return findings;
}

/** Reports source-tree leaks without copying the private path into another artefact. */
export function auditRepositoryHygiene(repo: RepositoryText) {
  const findings: HygieneFinding[] = [];
  let filesScanned = 0;
  for (const file of [...new Set(repo.files)].sort()) {
    if (OUTPUT_PATH.test(file))
      findings.push({
        file,
        line: 0,
        rule: "maintenance-output",
        message:
          "Generated run/log/maintenance material and private local configuration must remain ignored local state, outside source control.",
      });
    if (MEDIA_BINARY.test(file) && !TRACKED_MEDIA_FOLDERS.some((folder) => file.startsWith(folder)))
      findings.push({
        file,
        line: 0,
        rule: "media-binary",
        message:
          "Media binaries stay out of git: fetch it from a manifest with pnpm assets:sync (docs/assets.md), or add it to inventory row (c) and TRACKED_MEDIA_FOLDERS.",
      });
    const link = repo.linkTarget?.(file);
    if (link === undefined && !repo.exists(file)) continue;
    if (HOME_PATH.test(file) || WORKTREE_PATH.test(file))
      findings.push({
        file,
        line: 0,
        rule: "local-path",
        message: "File name contains a machine-specific home or harness-worktree path.",
      });
    if (link !== undefined) {
      filesScanned++;
      const target = link.replaceAll("\\", "/");
      const relative = path.posix.normalize(path.posix.join(path.posix.dirname(file), target));
      if (
        target.startsWith("/") ||
        /^[A-Za-z]:/.test(target) ||
        relative === ".." ||
        relative.startsWith("../") ||
        HOME_PATH.test(target) ||
        WORKTREE_PATH.test(target)
      )
        findings.push({
          file,
          line: 0,
          rule: "local-path",
          message: "Symlink target must be repository-relative and cannot escape the source tree.",
        });
      continue;
    }
    const text = repo.read(file);
    if (text === undefined || text.includes("\0")) continue;
    filesScanned++;
    text.split(/\r?\n/).forEach((line, index) => {
      const local = line.replace(/https?:\/\/[^\s"'`<>]+/gi, (raw) => {
        try {
          const url = new URL(raw);
          const data = `${url.search} ${url.hash} ${/^\/Users\//.test(url.pathname) ? url.pathname : ""}`;
          try {
            return decodeURIComponent(data);
          } catch {
            return data;
          }
        } catch {
          return raw;
        }
      });
      if (HOME_PATH.test(local) || WORKTREE_PATH.test(local))
        findings.push({
          file,
          line: index + 1,
          rule: "local-path",
          message:
            "Replace the machine-specific home/worktree path with a repository-relative path or an explicit runtime input; remove obsolete run artefacts.",
        });
    });
  }
  findings.push(...harnessFindings(repo, [...new Set(repo.files)].sort()));
  return {
    version: 1,
    filesScanned,
    findings,
    summary: {
      files: filesScanned,
      findings: findings.length,
      localPaths: findings.filter((finding) => finding.rule === "local-path").length,
      maintenanceOutputs: findings.filter((finding) => finding.rule === "maintenance-output").length,
      mediaBinaries: findings.filter((finding) => finding.rule === "media-binary").length,
      harnessLinks: findings.filter((finding) => finding.rule === "harness-link").length,
    },
  };
}
