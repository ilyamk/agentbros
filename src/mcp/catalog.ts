liveCommand.schema = liveCommand.schema.superRefine((value, ctx) => {
  const schema = ARSENAL_OP_SCHEMAS[String(value.action)];
  if (!schema) return;
  try {
    const result = schema.safeParse(JSON.parse(String(value.params ?? "{}")));
    if (!result.success) ctx.addIssue({ code: "custom", path: ["params"], message: result.error.message });
  } catch {
    ctx.addIssue({ code: "custom", path: ["params"], message: "params must be a JSON object string." });
  }
});
