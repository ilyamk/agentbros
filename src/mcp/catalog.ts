/** The tool's script comes from the one registry entry that names it (src/lib/cli/commands.ts). */
const scriptOf = (name: string): string => {
  const script = commandByMcpTool(name)?.script;
  if (!script?.startsWith("scripts/"))
    throw new Error(`MCP tool ${name} has no scripts/ entry in the command registry.`);
  return script.slice("scripts/".length);
};
const define = (
  name: string,
  description: string,
  fields: z.ZodRawShape,
  paths: string[] = [],
  spend: ToolCommand["paid"] = "local",
  readOnly = false,
): ToolCommand => ({
  name,
  script: scriptOf(name),
  description,
  schema: z.object(fields).strict(),
  paths,
  paid: spend,
  readOnly,
});
/** The bridge passes the trusted `--scope-root` (the launcher's workspace root) to this tool: its request, plan or manifest files name nested paths the script must contain. The script must declare `scope-root`. */
const withScopeRoot = (command: ToolCommand): ToolCommand => ({ ...command, scopeRoot: true });
